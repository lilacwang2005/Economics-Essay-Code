# ═══════════════════════════════════════════════════════════════════════════════
# 典型话题时序图
# ═══════════════════════════════════════════════════════════════════════════════
print("\n选择典型话题...")

topic_meta = panel.groupby("title").agg(
    earlyStance=("earlyStance_2h", "first"),
    n_windows=("窗口", "count"),
    overall_stance=("overall_stance", "first"),
    category=("category_L1", "first"),
).reset_index()

# 筛选窗口数 ≥ 20 的话题（时序足够长）
topic_meta = topic_meta[topic_meta["n_windows"] >= 20].copy()

# 分三组：强正锚（earlyStance > 40）、强负锚（earlyStance < -40）、中性锚（|earlyStance| < 10）
pos_pool = topic_meta[topic_meta["earlyStance"] >  40].nlargest(12, "earlyStance")
neg_pool = topic_meta[topic_meta["earlyStance"] < -40].nsmallest(12, "earlyStance")
neu_pool = topic_meta[topic_meta["earlyStance"].abs() < 10].sample(min(6, len(topic_meta[topic_meta["earlyStance"].abs() < 10])), random_state=42)

# 从每组选 3 个话题（总体锚定效应最明显 = 整体 stance 与 earlyStance 方向一致的）
def pick_representative(pool, n=3):
    """选整体 stance 与 earlyStance 方向最一致的话题"""
    pool = pool.copy()
    pool["consistency"] = pool["earlyStance"] * pool["overall_stance"]
    return pool.nlargest(n, "consistency")["title"].tolist()

pos_titles = pick_representative(pos_pool, 3)
neg_titles = pick_representative(neg_pool, 3)
# 中性组直接取前3
neu_titles = neu_pool["title"].tolist()[:3]

selected = pos_titles + neg_titles + neu_titles
print(f"  正向锚话题（{len(pos_titles)}个）：{pos_titles}")
print(f"  负向锚话题（{len(neg_titles)}个）：{neg_titles}")
print(f"  中性锚话题（{len(neu_titles)}个）：{neu_titles}")

# ── 绘图 ──────────────────────────────────────────────────────────────────────
fig, axes = plt.subplots(3, 3, figsize=(13, 9), sharey=False)

groups = [
    (tr(LANG, "正向早期锚", "Positive early anchor"), pos_titles, ECON_COLORS["blue"]),
    (tr(LANG, "负向早期锚", "Negative early anchor"), neg_titles, ECON_COLORS["red"]),
    (tr(LANG, "中性早期锚", "Neutral early anchor"), neu_titles, ECON_COLORS["green"]),
]

for row_idx, (group_name, titles, color) in enumerate(groups):
    for col_idx, title in enumerate(titles):
        ax = axes[row_idx][col_idx]
        sub = panel[panel["title"] == title].sort_values("窗口")
        early_val = sub["earlyStance_2h"].iloc[0]

        ax.plot(sub["小时_中点"], sub["stance_it"],
                color=color, linewidth=1.5, marker="o", markersize=3,
                label=tr(LANG, "窗口均值", "Window mean"))
        ax.axhline(early_val, color=color, linestyle="--", linewidth=1.2,
                   alpha=0.7, label=tr(LANG, "早期锚定值", "Early anchor"))
        ax.axhline(0, color="#AAAAAA", linestyle=":", linewidth=0.8)

        if len(sub) >= 5:
            smoothed = sub["stance_it"].rolling(3, center=True, min_periods=1).mean()
            ax.plot(sub["小时_中点"], smoothed, color=color, linewidth=2.2, alpha=0.35)

        ax.set_xlabel(tr(LANG, "上榜后小时数", "Hours after trending"), fontsize=9)
        ax.set_ylabel(tr(LANG, "平均态度得分", "Mean stance"), fontsize=9)
        ax.tick_params(labelsize=8)
        ax.set_xlim(left=0)
        ax.legend(fontsize=7, loc="upper right", framealpha=0.8)
        style_ax(ax)

plt.tight_layout()
