# ═══════════════════════════════════════════════════════════════════════════════
# 全样本评论态度标准差随窗口编号的均值演变（收敛趋势）
# ═══════════════════════════════════════════════════════════════════════════════
print("\n计算全样本收敛趋势...")

# 只保留有足够样本的窗口（各窗口编号下至少有 50 个话题有观测）
window_coverage = panel.groupby("窗口")["title"].count()
valid_windows = window_coverage[window_coverage >= 50].index
panel_valid = panel[panel["窗口"].isin(valid_windows)].copy()

# 按窗口聚合：均值 ± SE
conv = panel_valid.groupby("窗口").agg(
    mean_std=("stance_std_it", "mean"),
    se_std=("stance_std_it", lambda x: x.std() / np.sqrt(len(x))),
    n_topics=("title", "count"),
    mean_stance=("stance_it", "mean"),
    se_stance=("stance_it", lambda x: x.std() / np.sqrt(len(x))),
).reset_index()
conv["小时_中点"] = conv["窗口"] * 2 + 1

print(f"  有效窗口数：{len(conv)}，话题覆盖范围：{conv['n_topics'].min()}~{conv['n_topics'].max()} 个/窗口")

# ── 分 earlyStance 方向的子组趋势（正锚 vs 负锚）──
panel["anchor_group"] = panel["earlyStance_2h"].apply(
    lambda x: tr(LANG, "正向锚（>20）", "Positive (>20)") if x > 20 else (tr(LANG, "负向锚（<-20）", "Negative (<-20)") if x < -20 else tr(LANG, "中性锚（±20）", "Neutral (±20)"))
)
conv_by_group = {}
for grp_name, grp_df in panel_valid.groupby(
    panel_valid["title"].map(panel.drop_duplicates("title").set_index("title")["anchor_group"])
):
    agg = grp_df.groupby("窗口").agg(
        mean_std=("stance_std_it", "mean"),
        mean_stance=("stance_it", "mean"),
        n=("title", "count"),
    ).reset_index()
    agg["小时_中点"] = agg["窗口"] * 2 + 1
    conv_by_group[grp_name] = agg[agg["n"] >= 20]

# ── 绘图：左边全样本标准差，右边分组态度均值 ──
fig, axes = plt.subplots(1, 2, figsize=(12, 5))

# 左图：态度标准差随时间演变（收敛检验）
ax = axes[0]
ax.fill_between(conv["小时_中点"],
                conv["mean_std"] - 1.96 * conv["se_std"],
                conv["mean_std"] + 1.96 * conv["se_std"],
                alpha=0.15, color=ECON_COLORS["blue"])
ax.plot(conv["小时_中点"], conv["mean_std"],
        color=ECON_COLORS["blue"], linewidth=1.8, marker="o", markersize=4,
        label=tr(LANG, "全样本均值", "Full-sample mean"))

x_arr = conv["小时_中点"].values
y_arr = conv["mean_std"].values
coefs = np.polyfit(x_arr, y_arr, 1)
trend_y = np.polyval(coefs, x_arr)
ax.plot(x_arr, trend_y, color=ECON_COLORS["red"], linestyle="--", linewidth=1.5,
        label=tr(LANG, "线性趋势", "Linear trend"))

ax.set_xlabel(tr(LANG, "上榜后小时数", "Hours after trending"), fontsize=12)
ax.set_ylabel(tr(LANG, "评论态度标准差均值", "Mean stance standard deviation"), fontsize=12)
ax.legend(fontsize=10)
ax.set_xlim(left=0)
style_ax(ax)

# 右图：分组平均态度演变
ax = axes[1]
colors_map = {
    tr(LANG, "正向锚（>20）", "Positive (>20)"): ECON_COLORS["blue"],
    tr(LANG, "中性锚（±20）", "Neutral (±20)"): ECON_COLORS["green"],
    tr(LANG, "负向锚（<-20）", "Negative (<-20)"): ECON_COLORS["red"],
}
markers_map = {
    tr(LANG, "正向锚（>20）", "Positive (>20)"): "o",
    tr(LANG, "中性锚（±20）", "Neutral (±20)"): "s",
    tr(LANG, "负向锚（<-20）", "Negative (<-20)"): "^",
}
for grp_name, grp_conv in conv_by_group.items():
    c = colors_map.get(grp_name, ECON_COLORS["gray"])
    m = markers_map.get(grp_name, "o")
    ax.plot(grp_conv["小时_中点"], grp_conv["mean_stance"],
            color=c, linewidth=1.8, marker=m, markersize=4,
            label=grp_name)
ax.axhline(0, color="#AAAAAA", linestyle=":", linewidth=0.8)
ax.set_xlabel(tr(LANG, "上榜后小时数", "Hours after trending"), fontsize=12)
ax.set_ylabel(tr(LANG, "平均态度得分", "Mean stance"), fontsize=12)
ax.legend(fontsize=10)
ax.set_xlim(left=0)
style_ax(ax)

plt.tight_layout()
fig_a2_name = tr(LANG, "FigA2_全样本收敛趋势.pdf", "FigA2_ConvergenceTrends.pdf")
out_a2 = os.path.join(FIG, fig_a2_name)
plt.savefig(out_a2, dpi=300, bbox_inches="tight")
plt.close()
print(f"  → 已保存：{out_a2}")

# ── 打印收敛趋势摘要 ──
print("\n=== 描述性摘要 ===")
print(f"全样本态度标准差：")
print(f"  窗口0（前2h）：{conv['mean_std'].iloc[0]:.2f}")
print(f"  窗口末（{conv['小时_中点'].iloc[-1]:.0f}h）：{conv['mean_std'].iloc[-1]:.2f}")
print(f"  线性趋势斜率：{coefs[0]:.4f}（每2h变化）")
slope_pct = (conv['mean_std'].iloc[-1] - conv['mean_std'].iloc[0]) / conv['mean_std'].iloc[0] * 100
print(f"  首尾变化幅度：{slope_pct:.1f}%")

print("\n各组早期 vs 整体 stance 对比：")
for grp_name, grp_conv in conv_by_group.items():
    if len(grp_conv) > 0:
        early_v = grp_conv["mean_stance"].iloc[0]
        late_v = grp_conv["mean_stance"].iloc[-1]
        print(f"  {grp_name}：早期={early_v:.1f}，末期={late_v:.1f}，变化={late_v-early_v:.1f}")

print("\n完成。")
