def stat_row(ser, label, fmt=".2f"):
    """生成一行描述性统计（均值/标准差/最小值/P25/中位数/P75/最大值/观测数）"""
    s = ser.dropna()
    return {
        "var": latex_var_label(label),
        "mean": f"{s.mean():{fmt}}",
        "sd": f"{s.std():{fmt}}",
        "min": f"{s.min():{fmt}}",
        "p25": f"{s.quantile(0.25):{fmt}}",
        "median": f"{s.median():{fmt}}",
        "p75": f"{s.quantile(0.75):{fmt}}",
        "max": f"{s.max():{fmt}}",
        "obs": f"{len(s):,}",
    }

